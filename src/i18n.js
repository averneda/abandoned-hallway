let lang = 'es';

export function getLang() { return lang; }

export function setLang(l) {
  if (dict[l]) {
    lang = l;
    try { localStorage.setItem('holeway.lang', l); } catch (e) { /* sin almacenamiento */ }
  }
}

export function loadLang() {
  try {
    const saved = localStorage.getItem('holeway.lang');
    if (saved && dict[saved]) lang = saved;
  } catch (e) { /* sin almacenamiento */ }
  return lang;
}

// t('hud.level', {n: 3}) -> "Pasillo 3"
export function t(key, vars) {
  let s = (dict[lang] && dict[lang][key]) || dict.es[key] || key;
  if (vars) for (const k of Object.keys(vars)) s = s.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
  return s;
}
